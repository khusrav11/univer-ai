/* ================= I18N ENGINE =================
   Весь интерфейс пишется по-русски. Этот модуль переводит каждый текст
   на странице на казахский или английский по словарю I18N_DICT.
   Числа в тексте заменяются на {0}, {1}…, имена и названия — на {N0}, {N1}…,
   поэтому одна строка словаря подходит для любых значений.
   Пример: "19 из 35 · порог 50%"  →  ключ "{0} из {1} · порог {2}%". */
const I18N=(()=>{
  const LANGS={ru:-1,kk:0,en:1};
  const CYR=/[А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]/;
  const NUM=/\d+(?:[.,]\d+)*/g;
  const ATTRS=['placeholder','title','aria-label','value'];
  const SKIP={SCRIPT:1,STYLE:1};
  const srcMap=new WeakMap();     // узел → {src: русский оригинал, out: что показано}
  const attrMap=new WeakMap();    // элемент → {attr: {src,out}}
  const misses=new Set();         // ключи без перевода (для проверки)
  let termRe=null,termKeys=[];

  function buildTerms(){
    termKeys=Object.keys(I18N_TERMS).sort((a,b)=>b.length-a.length);
    const esc=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
    termRe=new RegExp('(?<![А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІіA-Za-z])('+termKeys.map(esc).join('|')+')(?![А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІіA-Za-z])','g');
  }
  function lang(){return (typeof S!=='undefined'&&S.lang)||'ru'}

  // Превращает текст в ключ словаря + списки имён и чисел
  function normalize(s){
    if(!termRe)buildTerms();
    const terms=[],nums=[];
    let k=s.replace(termRe,m=>{terms.push(m);return `{N${terms.length-1}}`});
    k=k.replace(/\{N(\d+)\}|\d+(?:[.,]\d+)*/g,(m,n)=>{if(n!==undefined)return m;nums.push(m);return `{${nums.length-1}}`});
    return {key:k,terms,nums};
  }
  function fill(tpl,terms,nums,L){
    const li=LANGS[L];
    return tpl.replace(/\{N(\d+)\}/g,(m,i)=>{const t=terms[+i];return li<0?t:((I18N_TERMS[t]||[])[li]??t)})
              .replace(/\{(\d+)\}/g,(m,i)=>{let v=nums[+i]??m;if(L==='en'&&/^\d+,\d+$/.test(v))v=v.replace(',','.');return v});
  }
  // Перевести одну строку
  function tr(src,L=lang()){
    if(L==='ru'||!src||!CYR.test(src))return src;
    const lead=src.match(/^\s*/)[0],trail=src.match(/\s*$/)[0],core=src.trim();
    if(!core)return src;
    const {key,terms,nums}=normalize(core);
    const e=I18N_DICT[key];let tpl;
    if(e)tpl=e[LANGS[L]];
    else if(!/[А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІіA-Za-z]/.test(key.replace(/\{N?\d+\}/g,'')))tpl=key; // только имена/числа
    else{misses.add(key);return src}
    return lead+fill(tpl,terms,nums,L)+trail;
  }
  function doText(node){
    const p=node.parentNode;if(!p||SKIP[p.nodeName])return;
    const cur=node.nodeValue,rec=srcMap.get(node);
    const src=(rec&&cur===rec.out)?rec.src:cur;
    if(!CYR.test(src)&&!rec)return;
    const out=tr(src);
    srcMap.set(node,{src,out});
    if(cur!==out)node.nodeValue=out;
  }
  function doAttrs(el){
    if(el.nodeType!==1)return;
    for(const a of ATTRS){
      if(!el.hasAttribute(a))continue;
      if(a==='value'&&!(el.tagName==='INPUT'&&(!el.type||el.type==='text')))continue;
      const cur=el.getAttribute(a);let m=attrMap.get(el);if(!m){m={};attrMap.set(el,m)}
      const rec=m[a],src=(rec&&cur===rec.out)?rec.src:cur;
      if(!CYR.test(src)&&!rec)continue;
      const out=tr(src);m[a]={src,out};
      if(cur!==out){el.setAttribute(a,out);if(a==='value')el.value=out}
    }
  }
  function apply(root=document.body){
    if(root.nodeType===3){doText(root);return}
    if(root.nodeType!==1)return;
    doAttrs(root);
    const w=document.createTreeWalker(root,NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT);
    let n;while((n=w.nextNode())){if(n.nodeType===3)doText(n);else doAttrs(n)}
  }
  let busy=false;
  const obs=new MutationObserver(list=>{
    if(busy)return;busy=true;
    try{for(const m of list){
      if(m.type==='characterData')doText(m.target);
      else if(m.type==='attributes')doAttrs(m.target);
      else m.addedNodes.forEach(apply);
    }}finally{busy=false}
  });
  function start(){apply(document.body);obs.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:ATTRS})}
  return {tr,apply,start,normalize,misses};
})();
